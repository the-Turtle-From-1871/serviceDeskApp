import type { DeviceClass } from "@prisma/client";

/**
 * The device CLASS rules: the loaner naming convention, and what a rename does
 * to `Item.deviceClass`.
 *
 * Pure — no Prisma runtime import, no React — so the rules unit-test directly
 * and can be imported by every path that writes a device name, the same reason
 * `readiness.ts` and `audit.status.ts` are split out. (`import type` erases at
 * compile time, so the enum type costs nothing at runtime.)
 *
 * This file was `loaner-name.ts` until 2026-10-19, when the `isLoaner` boolean
 * became a three-value class. The reasoning it carried is unchanged and is kept
 * below, because it is the reasoning for why LOANER follows the device name at
 * all.
 *
 * WHY LOANER FOLLOWS THE NAME. `isLoaner` shipped (2026-08-11, #129) as a purely
 * hand-set flag, and its schema comment said a person was "the only possible
 * source" precisely so a nightly import could not move it. That was reversed the
 * same day by explicit decision: the property manager already encodes loaner
 * status IN THE DEVICE NAME, and maintaining the same fact twice, once in Intune
 * and once here, is what guarantees the two disagree.
 *
 * THE CONSEQUENCE, stated plainly because it is the cost of that decision: MDM
 * owns `deviceName`, so MDM indirectly owns a device's loaner status. A device
 * renamed in Intune out of the convention stops being a loaner on the next
 * import without anyone here deciding that.
 *
 * STANDALONE IS DIFFERENT, AND DELIBERATELY SO: it has no naming convention and
 * is set by hand only. Nothing an import does can move a device into or out of
 * it. That is not an inconsistency with the rule above — it is the same rule
 * applied honestly. The loaner convention is derived from names because the
 * names really do encode it; no such convention exists for standalone devices,
 * so deriving one would be inventing a fact rather than reading one.
 */

/**
 * `NGHINB-LOAN-` followed by digits.
 *
 * ANCHORED, so a name that merely CONTAINS the word cannot match — a substring
 * rule would eventually catch something like `NGHINB-LOANER-DEPOT`.
 *
 * DIGITS ARE `+`, NOT `{3}`. The numbering has already reached 139; a
 * hundred-and-first loaner numbered 1000 silently ceasing to be one is a worse
 * failure than a two-digit name being accepted.
 *
 * CASE-INSENSITIVE, which deliberately DIVERGES from `isAutogeneratedDeviceName`
 * in import.ts. That one is case-sensitive because being too eager there wrongly
 * REFUSES a real rename — it errs toward doing nothing. This is a convention a
 * person types by hand into Intune or the edit form, so `nghinb-loan-140` is the
 * same intent as the uppercase spelling.
 *
 * KNOWN GAP, measured 2026-10-19 and deliberately NOT closed here: the live
 * fleet has moved on. Only 9 devices match this pattern, while 43 are named
 * `NGHINB-PLOAN###` — no hyphen, a `P` prefix — and carry no loaner marking at
 * all. Widening the pattern would silently reclassify those 43 and remove them
 * from the "dropped off the network" list, which is a property-book decision
 * rather than a refactor, so it is raised rather than taken.
 */
const LOANER_NAME = /^NGHINB-LOAN-\d+$/i;

export function isLoanerName(name: string | null | undefined): boolean {
  return typeof name === "string" && LOANER_NAME.test(name.trim());
}

/** The class a NEWLY CREATED device gets from its name. New rows have no class
 *  to preserve, so this is the whole rule: the convention, or the default. */
export function deviceClassForNewName(name: string | null | undefined): DeviceClass {
  return isLoanerName(name) ? "LOANER" : "EUD";
}

/**
 * What a rename does to the class.
 *
 * Returns a PARTIAL — `{}` means "leave `deviceClass` exactly as it is" — so the
 * three cases stay distinguishable at every call site:
 *
 *   into the convention                      -> `{ deviceClass: "LOANER" }`
 *   out of the convention, and it WAS LOANER -> `{ deviceClass: "EUD" }`
 *   anything else                            -> `{}`
 *
 * THE EMPTY CASE IS LOAD-BEARING. It preserves a class set by hand on a device
 * whose name says nothing: `NGHINB-PMACN128` becoming `NGHINB-PMACN129` is
 * evidence about nothing, and an unrelated rename must not quietly reclassify a
 * device.
 *
 * `currentClass` IS READ FOR EXACTLY ONE REASON — to keep a hand-set STANDALONE
 * from being clobbered — and the boolean version of this function deliberately
 * did NOT read the flag, so the change deserves its reasoning. The old rule was
 * "left the convention -> false". Applied literally to three values that becomes
 * "left the convention -> EUD", which would silently demote a STANDALONE device
 * that happened to be named `NGHINB-LOAN-005` the moment anyone renamed it. The
 * old objection to reading current state was that it made the function
 * idempotent in the wrong direction — re-asserting `false` over a hand-set
 * `true` on every edit. That objection does not apply here, because the class is
 * read only to answer "was this a LOANER?", never to decide whether the new name
 * is one. A device that is not currently a LOANER is left alone.
 */
export function deviceClassForRename(
  previousName: string | null | undefined,
  nextName: string | null | undefined,
  currentClass: DeviceClass,
): { deviceClass?: DeviceClass } {
  if (isLoanerName(nextName)) return { deviceClass: "LOANER" };
  if (isLoanerName(previousName) && currentClass === "LOANER") return { deviceClass: "EUD" };
  return {};
}

/** How a class is written for a person. Centralised so the item page, the
 *  /items column, the bulk menu and the filter chip cannot disagree. */
export const DEVICE_CLASS_LABEL: Record<DeviceClass, string> = {
  EUD: "EUD",
  LOANER: "Loaner",
  STANDALONE: "Standalone",
};

/** Display order for pickers and filters: the default first, then the two
 *  exceptions in the order they were added. */
export const DEVICE_CLASS_ORDER: readonly DeviceClass[] = ["EUD", "LOANER", "STANDALONE"] as const;

/** Whether an arbitrary string is a class. Used to validate a querystring value
 *  before it reaches a `where`, so a crafted `?class=` cannot reach the DB. */
export function isDeviceClass(v: string | null | undefined): v is DeviceClass {
  return typeof v === "string" && (DEVICE_CLASS_ORDER as readonly string[]).includes(v);
}
